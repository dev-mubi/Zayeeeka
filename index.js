const express = require("express");
const mongoose = require("mongoose");
const cors = require("cors");
const QR = require("./QR");
const directive = require("./Directives");
const Admin = require("./Admin");
const Food_items = require("./fooditems");
const meneu = require("./FoodMeneue");
require("dotenv").config();

// -------------------------------------------------------------------------------

const app = express();
app.use(cors());
app.use(express.json());

mongoose.connect(process.env.MONGO_URI, {
  useNewUrlParser: true,
  useUnifiedTopology: true,
});

// -------------------------------------------------------------------------------

app.post("/store-qr", async (req, res) => {
  try {
    const { orderId, mess, date, dish } = req.body;

    const newQR = new QR({ orderId, mess, date, dish });
    await newQR.save();

    res.json({ message: "QR data saved successfully" });
  } catch (error) {
    res.status(500).json({ error: "Failed to save QR data" });
  }
});

// -------------------------------------------------------------------------------

app.post("/login", async (req, res) => {
  const { username, password } = req.body;

  const user = await Admin.findOne({ username });

  if (user) {
    if (password === user.password) {
      res.json({ message: "Login successful", user });
    } else {
      res.status(401).json({ message: "Invalid password" });
    }
  } else {
    res.status(404).json({ message: "User not found" });
  }
});
// -------------------------------------------------------------------------------

const FeedbackModel = require("./FeedbackModel");

app.post("/submit-feedback", async (req, res) => {
  const { orderId, mess, date, rating, comment } = req.body;

  try {
    const qrExists = await QR.findOne({ orderId });
    if (!qrExists) {
      return res.status(400).json({
        error: "Invalid QR code. This order was not generated by admin.",
      });
    }

    const feedback = new FeedbackModel({
      orderId,
      mess,
      date,
      rating,
      comment,
    });

    await feedback.save(); // 100 if feedback already submitted.

    res.status(200).json({ message: "Feedback submitted successfully." });
  } catch (err) {
    if (err.code === 11000) {
      return res.status(399).json({
        error: "Feedback has already been submitted for this order.",
      });
    }

    console.error("Unexpected error while submitting feedback:", err);
    res.status(500).json({
      error: "An unexpected error occurred while submitting feedback.",
    });
  }
});

