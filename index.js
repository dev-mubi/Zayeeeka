app.get("/feedback-summary", async (req, res) => {
  const { mess } = req.query;

  if (!mess) {
    return res.status(400).json({ error: "Mess name is required." });
  }

  try {
    const totalOrders = await QR.countDocuments({ mess });
    const feedbacksReceived = await FeedbackModel.countDocuments({ mess });

    res.json({ totalOrders, feedbacksReceived });
  } catch (err) {
    console.error("Error in /feedback-summary:", err);
    res.status(500).json({ error: "Internal server error" });
  }
});
