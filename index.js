app.get("/analytics", async (req, res) => {
  const { mess } = req.query;

  if (!mess) {
    return res.status(400).json({ error: "Mess name is required." });
  }

  try {
    const feedbacks = await FeedbackModel.find({ mess });

    let total = 0;

    let one = 0;
    let two = 0;
    let three = 0;
    let four = 0;
    let five = 0;

    for (let i = 0; i < feedbacks.length; i++) {
      const rating = parseInt(feedbacks[i].rating);

      if (rating === 1) {
        one++;
        total += 1;
      } else if (rating === 2) {
        two++;
        total += 2;
      } else if (rating === 3) {
        three++;
        total += 3;
      } else if (rating === 4) {
        four++;
        total += 4;
      } else if (rating === 5) {
        five++;
        total += 5;
      }
    }

    const averageRating =
      feedbacks.length === 0 ? 0 : (total / feedbacks.length).toFixed(2);

    res.json({
      averageRating,
      ratingCounts: {
        1: one,
        2: two,
        3: three,
        4: four,
        5: five,
      },
    });
  } catch (err) {
    console.error("Error in /analytics:", err);
    res.status(500).json({ error: "Internal server error" });
  }
});
