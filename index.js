app.get("/api/student-menu", async (req, res) => {
  const { mess } = req.query;

  if (!mess) {
    return res.status(400).json({ error: "Mess name is required." });
  }

  const today = new Date()
    .toLocaleDateString("en-GB", {
      timeZone: "Asia/Karachi", // Or your actual time zone
      day: "2-digit",
      month: "long",
      year: "numeric",
    })
    .replace(/ /g, "-");

  try {
    const menu = await meneu.findOne({ mess, date: today });

    if (!menu) {
      return res.status(204).json({ message: "No menu found for today." });
    }

    res.status(200).json(menu);
  } catch (err) {
    console.error("Error fetching today's menu:", err);
    res.status(500).json({ error: "Internal server error." });
  }
});

