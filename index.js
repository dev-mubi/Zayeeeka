const FeedbackModel = require("./FeedbackModel");

app.post("/submit-feedback", async (req, res) => {
  const { orderId, mess, date, rating, comment } = req.body;

  try {
    const qrExists = await QR.findOne({ orderId });
    if (!qrExists) {
      return res.status(400).json({
        error: "Invalid QR code. This order was not generated by admin.",
      });
    }

    const feedback = new FeedbackModel({
      orderId,
      mess,
      date,
      rating,
      comment,
    });

    await feedback.save(); // 100 if feedback already submitted.

    res.status(200).json({ message: "Feedback submitted successfully." });
  } catch (err) {
    if (err.code === 11000) {
      return res.status(399).json({
        error: "Feedback has already been submitted for this order.",
      });
    }

    console.error("Unexpected error while submitting feedback:", err);
    res.status(500).json({
      error: "An unexpected error occurred while submitting feedback.",
    });
  }
});

